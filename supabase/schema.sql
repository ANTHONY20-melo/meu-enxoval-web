-- ------------------------------------------------------------
-- 1. TABELA: e-mails dos administradores (o casal)
-- ------------------------------------------------------------
create table if not exists public.admin_emails (
  email text primary key,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 2. TABELA: reservas de presentes feitas pelos convidados
--    item_key   = "enxoval:categoria:item" (mesma chave do checklist)
--    guest_name = nome digitado pelo convidado
--    Uma única reserva por item (unique).
-- ------------------------------------------------------------
create table if not exists public.gift_reservations (
  id bigint generated by default as identity primary key,
  item_key text not null unique,
  guest_name text not null,
  created_at timestamptz not null default now()
);

create index if not exists gift_reservations_item_key_idx
  on public.gift_reservations (item_key);

-- ------------------------------------------------------------
-- 3. FUNÇÃO: o usuário logado é administrador?
-- ------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_emails
    where email = auth.jwt() ->> 'email'
  );
$$;

-- ------------------------------------------------------------
-- 4. FUNÇÃO: primeiro acesso do casal (máx. 2 admins)
--    Cada membro do casal loga e clica em "Tornar-me admin".
-- ------------------------------------------------------------
create or replace function public.claim_admin()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := auth.jwt() ->> 'email';
begin
  if v_email is null then
    return false;
  end if;

  if (select count(*) from public.admin_emails) >= 2 then
    return false;
  end if;

  if exists (
    select 1 from public.admin_emails where email = v_email
  ) then
    return true;
  end if;

  insert into public.admin_emails (email) values (v_email);
  return true;
end;
$$;

-- ------------------------------------------------------------
-- 5. FUNÇÃO: reservar um presente (convidado)
--    Retorna true se reservou, false se já está reservado.
-- ------------------------------------------------------------
create or replace function public.reserve_gift(
  p_item_key text,
  p_guest_name text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_item_key is null or p_item_key = '' then
    return false;
  end if;

  p_guest_name := trim(p_guest_name);

  if p_guest_name is null or length(p_guest_name) < 2
     or length(p_guest_name) > 80 then
    return false;
  end if;

  insert into public.gift_reservations (item_key, guest_name)
  values (p_item_key, p_guest_name)
  on conflict (item_key) do nothing;

  return found;
end;
$$;

-- ------------------------------------------------------------
-- 6. FUNÇÃO: cancelar a própria reserva (convidado)
--    Só cancela se o nome bater com a reserva.
-- ------------------------------------------------------------
create or replace function public.cancel_gift(
  p_item_key text,
  p_guest_name text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.gift_reservations
  where item_key = p_item_key
    and lower(guest_name) = lower(trim(p_guest_name));

  return found;
end;
$$;

-- ------------------------------------------------------------
-- 7. FUNÇÃO: cancelar reserva como administrador
-- ------------------------------------------------------------
create or replace function public.cancel_gift_admin(
  p_item_key text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    return false;
  end if;

  delete from public.gift_reservations
  where item_key = p_item_key;

  return found;
end;
$$;

-- ------------------------------------------------------------
-- 8. GRANTS (quem pode chamar as funções)
-- ------------------------------------------------------------
grant execute on function public.is_admin() to authenticated;
grant execute on function public.claim_admin() to authenticated;
grant execute on function public.reserve_gift(text, text)
  to anon, authenticated;
grant execute on function public.cancel_gift(text, text)
  to anon, authenticated;
grant execute on function public.cancel_gift_admin(text)
  to authenticated;

-- ------------------------------------------------------------
-- 9. ROW LEVEL SECURITY
-- ------------------------------------------------------------
alter table public.admin_emails
  enable row level security;
alter table public.gift_reservations
  enable row level security;
alter table public.couple_checklist
  enable row level security;
alter table public.couple_budget
  enable row level security;

-- --------------------------------------
-- admin_emails: cada usuário só vê o próprio e-mail
-- --------------------------------------
drop policy if exists "admin_emails_select_self"
  on public.admin_emails;
create policy "admin_emails_select_self"
  on public.admin_emails
  for select to authenticated
  using (email = auth.jwt() ->> 'email');

-- --------------------------------------
-- gift_reservations: leitura pública (todos veem
-- quem reservou), escrita apenas via funções (RPC)
-- --------------------------------------
drop policy if exists "gift_reservations_select_public"
  on public.gift_reservations;
create policy "gift_reservations_select_public"
  on public.gift_reservations
  for select to anon, authenticated
  using (true);

-- --------------------------------------
-- couple_checklist: qualquer visitante PODE LER
-- (a lista de presentes é pública), mas só o casal
-- pode marcar/adicionar/remover itens
-- --------------------------------------
drop policy if exists "couple_checklist_select_public"
  on public.couple_checklist;
create policy "couple_checklist_select_public"
  on public.couple_checklist
  for select to anon, authenticated
  using (true);

drop policy if exists "couple_checklist_write_admin"
  on public.couple_checklist;
create policy "couple_checklist_write_admin"
  on public.couple_checklist
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- --------------------------------------
-- couple_budget: 100% privado — somente o casal
-- --------------------------------------
drop policy if exists "couple_budget_admin_all"
  on public.couple_budget;
create policy "couple_budget_admin_all"
  on public.couple_budget
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());
